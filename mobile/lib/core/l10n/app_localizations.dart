      _AppLocalizationsDelegate();

  static AppLocalizations of(BuildContext context) {
    return Localizations.of<AppLocalizations>(context, AppLocalizations)!;
  }

  String get languageCode => locale.languageCode;

  /// Look up [key]; falls back to Uzbek, then to the key itself.
  String t(String key) {
    final Map<String, String>? table = _values[languageCode];
    return table?[key] ?? _values['uz']?[key] ?? key;
  }

  /// Look up [key] and substitute `{name}` placeholders.
  String tp(String key, Map<String, Object?> params) {
    String text = t(key);
    params.forEach((String name, Object? value) {
      text = text.replaceAll('{$name}', '${value ?? ''}');
    });
    return text;
  }

  /// Pick the right string out of an API field like `{"uz": "...", "ru": "..."}`.
  String fromMap(Map<String, dynamic>? map, {String fallback = ''}) {
    if (map == null) return fallback;
    final Object? exact = map[languageCode];
    if (exact is String && exact.isNotEmpty) return exact;
    final Object? uz = map['uz'];
    if (uz is String && uz.isNotEmpty) return uz;
    return fallback;
  }

